# -*- coding: utf-8 -*-
'''
黑话基座词表（seed）—— 进库、可 review、可 diff 的**唯一人工数据源**。

为什么要单独抽一个 seed 文件：
    slang_dict.json / slang_replies.json 是**运行时真源**，已被 .gitignore 第 39/40 行
    排除（Lite 包不分发词典，用户自建）。直接把几百条写进那个文件，等于改了一个
    不在仓库里的文件 —— 换台机器就没法 review，也没法回滚。所以人工数据放这里，
    build_slang_seed.py 负责把它编译成运行时那两个 JSON。

数据形状：
    每条 = (词, 释义, [接话模板, ...])

    · 释义：**必须单行**，格式 `圈层｜一句人话`。注入时原样拼进提示词
      （slang_injector.get_context_for_llm 里是 f'{i}. {term}：{meaning}'），
      带换行会把编号列表打断；带「文化影响：…」这种论文腔既白烧 token 又不给语感
      —— 原运行版 105 条里绝大多数是这种。
    · 接话：空列表合法（低频词只给释义）。写进去的必须是**群里真实的回法**，
      不是解释句 —— 注入层原样塞给模型当语气参考（' / '.join(r)），
      写成解释句模型就学着解释去了。

收录判据（三条，缺一不收）：
    1. 模型不知道这个词 → 收（yyds / 蚌埠住了 / 水灵灵地）
    2. 模型知道，但语感会用错 → 收（破防 / 典 / 急了 —— 都短促带攻击性，
       模型爱写成「我理解你的感受」这种完整句）
    3. 模型知道且没特殊语感 → **不收**（上线 / 会议 / 重构 / 有道理 / 学到了）

刻意不收（曾进过运行版 105 条，剔除名单与理由在 build_slang_seed.py）：
    单字词（乐/润/孝 —— 子串匹配必中「音乐」「利润」「孝顺」）、
    通用词（有道理/学到了/长知识/涨姿势/开眼界/真的假的/不愧是你）、
    高歧义游戏词（基地/运营/意识/timing —— 「我在基地」「这公司运营不错」全中）、
    模型自带知识的普通词（AI/模型/提示词/重构 —— 收了纯占位还稀释权重）。

维护方式：
    加词就在对应圈层列表里追加一行；改释义直接改；改完跑
        python scripts/build_slang_seed.py --app '<resources\\app>' --dry-run
    dry-run 会报重复词、超长释义、禁用字符、单字词风险，确认后再去掉 --dry-run。
'''

