# -*- coding: utf-8 -*-
"""tests/test_prompt_segment_dedup.py —— prompt 段精简后的语义锚点（1.5.8 #28）

背景
    计划 #28：「【别怕不体面】【怎么接话】两段合计 35%，是预算大头。
    压短但要有回归判据」。

    两轮精简：
      第一轮（2026-10-24）只删字面重复 —— 三处，1155 → 1111（-44）。
        字面重复少是因为这两段的规则**彼此不同**：
          · 【别怕不体面】"不拿对方家人开刀" 说了两遍（第 2 条 + 最后一条）
          · 【别怕不体面】"不用给台阶/不用道歉" 散在两条里
          · 【怎么接话】"别要求对方给内容" 在【别催人回答】和【往下推】各说一遍

      第二轮（2026-10-25）删**无法测试的修辞性解释**，1111 → 970（-141）。
        参照 bostonaholic/dotfiles 的 prompt 规范：
          「每一行都必须有其存在的理由。如果你无法测试它，就删掉它。」
          「结构胜过花哨。具体例子胜过抽象指令。」
        以及 mi-gpt（同为 QQ 机器人）的提示：过长的提示语会消耗更多 token。
        具体删的是：举例堆叠（三个例子留两个）、同义反复的补充句、
        "这不是尺度问题，是底线" 这类不改变行为的强调。

    **没有**为了凑数字删掉任何一条规则，也没有把形容词规则改写成数字判据
    —— 后者是行为变更，需要在真实群里抽测。

    判据两条：
      1. **语义锚点一个都不能少** —— 每条规则留一个锚词，删了规则立刻红，
         而不是等用户在群里发现 bot 开始骂人或开始催人回答。
      2. **字符预算**（第 7 组）—— 涨回去也红。不做上限的话，
         "以后再精简"永远只是句口号。

纯 Python，不依赖浏览器。
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, ROOT)

import bot_core as bc  # noqa: E402

PASS = 0
FAIL = 0
FAILURES = []


def check(name, cond, extra=""):
    global PASS, FAIL
    if cond:
        PASS += 1
        print(f"  [OK]   {name}")
    else:
        FAIL += 1
        FAILURES.append(name + (f"  → {extra}" if extra else ""))
        print(f"  [FAIL] {name}  {extra}")


def main():
    segs = dict(bc.render_prompt_segments(True))
    rude = segs.get("别怕不体面", "")
    take = segs.get("怎么接话", "")
    total = sum(len(t) for t in segs.values())

    print("[1] 两段都还在，且没被删空")
    check("别怕不体面 存在且非空", len(rude) > 400, len(rude))
    check("怎么接话 存在且非空", len(take) > 400, len(take))
    # 原断言是「两段占总量 >30%」。加一条全局规则后总量变大，比例自然下降，
    # 断言会误报 —— 它想守的是"这两段没被削"，不是"别的段不许长"。
    # 改成绝对量：两段合计不许低于 900（当前 970）。
    check("两段合计仍 ≥900 字符（没被削）",
          len(rude) + len(take) >= 900, len(rude) + len(take))

    print("\n[2] 【可以凶】的语义锚点（骂人尺度，删任何一条都是行为变更）")
    RUDE_ANCHORS = [
        ("只在被挑衅时开火", "被扣帽子"),
        ("日常不带脏字", "不要带脏字"),
        ("可用脏字清单", "操、草、靠"),
        ("家人是底线", "不拿对方家人开刀"),
        ("要比对方更凶", "比对方更凶"),
        ("阴阳也是骂", "装没听懂再讽刺回去"),
        ("不用文诌诌的词", "别用文诌诌的词"),
        ("可以只发图", "可以只发一张图什么都不写"),
        ("隐私不开刀", "拿真实可查的隐私开刀"),
        ("连发受字数限制", "单次回复字数限制"),
    ]
    for name, kw in RUDE_ANCHORS:
        check("骂人尺度锚点：" + name, kw in rude, rude[:80])

    print("\n[3] 【怎么接话】的语义锚点")
    TAKE_ANCHORS = [
        ("先看时间", "【先看时间】"),
        ("时间矛盾要怼回去", "直接怼回去"),
        ("别顺着错前提答", "别顺着错的前提答"),
        ("话题跟着对方走", "【话题跟着对方走】"),
        ("别拽回旧话题", "拽回来追问"),
        ("别催人回答", "【别催人回答】"),
        ("别把球踢过去", "别把球踢过去"),
        ("往下推", "【往下推】"),
        ("说具体的事", "正在发生的、具体的事"),
        ("别问说点啥", "说点啥"),
        ("最多一个问题", "最多一个问题"),
    ]
    for name, kw in TAKE_ANCHORS:
        check("接话锚点：" + name, kw in take, take[:80])

    print("\n[4] 字面重复确实被删掉了（这是本次精简的唯一内容）")
    check("「不拿对方家人开刀」只出现一次",
          rude.count("不拿对方家人开刀") == 1, rude.count("不拿对方家人开刀"))
    check("「我们冷静一下」只出现一次",
          rude.count("我们冷静一下") == 1, rude.count("我们冷静一下"))
    check("「不过我也理解你」只出现一次",
          rude.count("不过我也理解你") == 1, rude.count("不过我也理解你"))
    check("「别要求对方给你安排任务」已删（与【别催人回答】重复）",
          "别要求对方给你安排任务" not in take)
    check("「那你倒是使唤我干点啥」已删（同上）",
          "那你倒是使唤我干点啥" not in take)

    print("\n[5] 合并后的句子仍说清了两件事")
    check("「事后不找补」同时覆盖给台阶和道歉",
          "不用给台阶" in rude and "不用道歉" in rude)
    check("隐私与家人分成两条讲，不再挤在「只有两件」里",
          "只有一件" in rude)

    print("\n[6] 没有偷偷加新规则")
    # 锚点数量是 21 个；若有人往里加规则，这里会提示同步锚点表
    n_anchors = len(RUDE_ANCHORS) + len(TAKE_ANCHORS)
    check("锚点表覆盖 %d 条（加规则请同步加锚点）" % n_anchors, n_anchors == 21, n_anchors)

    print("\n[7] ★ 字符预算（防止以后再涨回去）")
    # 2026-10-25 第二轮精简：两段 1111 → 970（-141）。
    # 判据取自 bostonaholic/dotfiles 的 prompt 规范：
    #   「每一行都必须有其存在的理由。如果你无法测试它，就删掉它。」
    # 以及 mi-gpt 的提示：「过长的提示语会消耗更多 token，请按需配置」。
    #
    # 这两条数额是**当前实测值 + 一点余量**，不是拍的：
    #   别怕不体面 504 → 上限 560
    #   怎么接话   466 → 上限 520
    #   段总量    2955 → 上限 3200
    # 2026-10-25 晚：新增【别露后台】【别拿反问续话】两条群聊规则（线上
    # 「我收到的原文长这样」汇报腔），段总量 2955 → 3168。上限调到 3200；
    # 两条规则都有线上实证，不是凑数。比例阈值不变（两段仍是 >30%）。
    #
    # 2026-10-27（1.5.9 §A.5）：诚实铁律加第 4 条「不假装不会」——编造"不能做"
    # 和编造"做了"同样是撒谎，而旧 prompt 只有前三条。第 4 条已压到最紧
    # （281 → 170 字符），段总量 3168 → 3338，上限相应调到 3350。
    # 想再加规则就得先删等量的字，或者明确调高上限并说明理由 ——
    # 不做上限的话，"以后再精简"永远只是句口号。
    check("别怕不体面 ≤ 560 字符", len(rude) <= 560, len(rude))
    check("怎么接话 ≤ 520 字符", len(take) <= 520, len(take))
    check("全部段合计 ≤ 3350 字符", total <= 3350, total)
    print(f"       实测：别怕不体面 {len(rude)} / 怎么接话 {len(take)} / 合计 {total}")

    print("\n" + "=" * 56)
    print(f"通过 {PASS} / 失败 {FAIL}")
    if FAILURES:
        print("失败项：")
        for f in FAILURES:
            print("  -", f)
    return 1 if FAIL else 0


if __name__ == "__main__":
    sys.exit(main())